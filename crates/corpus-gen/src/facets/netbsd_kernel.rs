//! The NetBSD kernel: its flag line, its link sets and its ident strings.
//!
//! Every case is built with the flag line of an amd64 NetBSD kernel unit, from `sys/conf/Makefile.kern.inc` and `sys/arch/amd64/conf/Makefile.amd64` at NetBSD trunk 3c50f5978, the tree that tamnd/rucc-bsd builds.
//! That line has `-ffreestanding`, `-fno-zero-initialized-in-bss`, `-fno-common`, `-fno-strict-aliasing`, `-fno-delete-null-pointer-checks`, `-ftrivial-auto-var-init=pattern` (`COPT_AUTOINIT`), `-mcmodel=kernel`, `-mno-red-zone`, no MMX, SSE or AVX, `-msoft-float`, and the retpoline flags `-mindirect-branch=thunk` and `-mindirect-branch-register`.
//! The cases add `-fcf-protection=none`, because GCC does not take the retpoline flags with the control flow protection that some distributions turn on by default, and `-fno-pie -no-pie`, so that a program built for the kernel code model runs in user space, as in `mcmodel-kernel`.
//! The line has `-std=gnu11` too, which the cases leave out, because the runner gives the dialect.
//!
//! `zero-in-data` checks that an object with a zero initializer is in `.data` and not in `.bss`, and that one with no initializer is in `.bss`.
//! The other cases are the kernel's own uses of what the line must keep working: `__KERNEL_RCSID` and `__KERNEL_COPYRIGHT` strings, `MODULE` entries in the `modules` link set with the dummy entry of `kern_module.c`, `SYSCTL_SETUP` functions in the `sysctl_funcs` link set called through the retpoline thunk, and a jump table.
//! The link set declaration of trunk makes the stop symbol weak and hidden with a top level `asm`, and the kernel writes it inside a function, so the cases do too.
//!
//! All the cases need an ELF linker and are x86-64 code.

use crate::Sink;
use crate::emit::Program;
use crate::facets::bsd_asm::{ELF_TYPES, MERGE_STRINGS, PROGBITS, SECTION_WALK, section};
use crate::lang::Ty;
use corpus_model::{Axes, Case, Dialect, Expect, Facet, Unit};

/// Where the cases come from.
const NETBSD: &str = "provenance:netbsd";

/// The flag line of an amd64 kernel unit, with the flags that let the program run in user space.
const FLAG_LINE: &[&str] = &[
    "-ffreestanding",
    "-fno-zero-initialized-in-bss",
    "-fno-delete-null-pointer-checks",
    "-fno-strict-aliasing",
    "-fno-common",
    "-ftrivial-auto-var-init=pattern",
    "-fno-omit-frame-pointer",
    "-mcmodel=kernel",
    "-mno-red-zone",
    "-mno-mmx",
    "-mno-sse",
    "-mno-avx",
    "-msoft-float",
    "-mindirect-branch=thunk",
    "-mindirect-branch-register",
    "-fcf-protection=none",
    "-fno-pie",
    "-no-pie",
];

/// The shapes of the facet.
const SHAPES: &[&str] =
    &["zero-in-data", "kernel-rcsid", "module-set", "sysctl-setup", "switch-thunk"];

/// What a case is.
struct Shape {
    /// The file the case has the shape of.
    after: &'static str,
    /// The C above `main`.
    top: Vec<String>,
    /// The other units, by name.
    units: Vec<(&'static str, Vec<String>)>,
    /// What `main` prints, as an `unsigned int` expression and its value.
    checks: Vec<(&'static str, i128)>,
}

/// Emits every case of the facet.
pub(crate) fn generate(sink: &mut Sink<'_>) {
    for &shape in SHAPES {
        if !sink.wants(Facet::NetbsdKernel) {
            break;
        }
        let found = shape_of(shape);
        let mut program = Program::new(format!("{shape} after {}", found.after));
        for line in &found.top {
            program.top(line.clone());
        }
        for &(expr, value) in &found.checks {
            program.check(Ty::U32, expr, value);
        }
        let (source, expected) = program.finish();
        let units = found
            .units
            .iter()
            .map(|(name, text)| {
                let mut out = format!(
                    "// The {name} unit of the {shape} case.\n// Generated by rucc-corpus. Edit the generator, not this file.\n\n"
                );
                for line in text {
                    out.push_str(line);
                    out.push('\n');
                }
                Unit::new(*name, out)
            })
            .collect();
        let case = Case::linked(
            Facet::NetbsdKernel,
            Axes::of([("shape", shape)]),
            Dialect::C17,
            source,
            units,
            FLAG_LINE.iter().map(|flag| (*flag).to_owned()).collect(),
            Expect::Output(expected),
        )
        .tagged(&["gnu", "elf", "x86-64", NETBSD]);
        sink.push_case(case);
    }
}

/// Owned lines from string slices.
fn lines(parts: &[&[&str]]) -> Vec<String> {
    parts.concat().iter().map(|line| (*line).to_owned()).collect()
}

/// The parts of `sys/sys/cdefs.h` and `sys/sys/cdefs_elf.h` at trunk 3c50f5978 that the cases use.
const CDEFS: &[&str] = &[
    "#define __CONCAT(x, y) x##y",
    "#define __STRING(x) #x",
    "#define __used __attribute__((__used__))",
    "#define __weak __attribute__((__weak__))",
    "#define __section(x) __attribute__((__section__(x)))",
    "#define __dso_hidden __attribute__((__visibility__(\"hidden\")))",
    "#define NULL ((void *)0)",
    "",
    "#define __SECTIONSTRING(_sec, _str) \\",
    "    __asm(\".pushsection \" #_sec \",\\\"MS\\\",@progbits,1\\n\" \\",
    "          \".asciz \\\"\" _str \"\\\"\\n\" \\",
    "          \".popsection\")",
    "#define __IDSTRING(_n, _s) __SECTIONSTRING(.ident, _s)",
    "#define __RCSID(_s) __IDSTRING(rcsid, _s)",
    "#define __COPYRIGHT(_s) __SECTIONSTRING(.copyright, _s)",
    "#define __KERNEL_RCSID(_n, _s) __RCSID(_s)",
    "#define __KERNEL_COPYRIGHT(_n, _s) __COPYRIGHT(_s)",
    "",
    "#define __link_set_make_entry(set, sym) \\",
    "    static void const *const __link_set_##set##_sym_##sym __section(\"link_set_\" #set) \\",
    "        __used = (const void *)&sym",
    "#define __link_set_add_text(set, sym) __link_set_make_entry(set, sym)",
    "#define __link_set_add_rodata(set, sym) __link_set_make_entry(set, sym)",
    "#define __link_set_start(set) (__start_link_set_##set)",
    "#define __link_set_end(set) (__stop_link_set_##set)",
    "#define __link_set_decl(set, ptype) \\",
    "    extern ptype *const __link_set_start(set)[] __dso_hidden; \\",
    "    __asm__(\".hidden \" __STRING(__stop_link_set_##set)); \\",
    "    extern ptype *const __link_set_end(set)[] __weak __dso_hidden",
    "#define __link_set_count(set) (__link_set_end(set) - __link_set_start(set))",
    "#define __link_set_foreach(pvar, set) \\",
    "    for (pvar = __link_set_start(set); pvar < __link_set_end(set); pvar++)",
    "",
];

/// `MODULE` from `sys/sys/module.h`, as a kernel built with link sets has it.
const MODULE_H: &[&str] = &[
    "typedef enum modcmd {",
    "    MODULE_CMD_INIT,",
    "    MODULE_CMD_FINI,",
    "    MODULE_CMD_STAT,",
    "    MODULE_CMD_AUTOUNLOAD,",
    "} modcmd_t;",
    "",
    "typedef struct modinfo {",
    "    unsigned int mi_version;",
    "    int mi_class;",
    "    int (*mi_modcmd)(modcmd_t, void *);",
    "    const char *mi_name;",
    "    const char *mi_required;",
    "} const modinfo_t;",
    "",
    "#define _MODULE_REGISTER(name) __link_set_add_rodata(modules, __CONCAT(name, _modinfo));",
    "#define MODULE(class, name, required) \\",
    "    static int __CONCAT(name, _modcmd)(modcmd_t, void *); \\",
    "    static const modinfo_t __CONCAT(name, _modinfo) = { \\",
    "        .mi_version = 1199001000u, \\",
    "        .mi_class = (class), \\",
    "        .mi_modcmd = __CONCAT(name, _modcmd), \\",
    "        .mi_name = __STRING(name), \\",
    "        .mi_required = (required)}; \\",
    "    _MODULE_REGISTER(name)",
    "",
];

/// `SYSCTL_SETUP` from `sys/sys/sysctl.h`, for a unit that is not a module.
const SYSCTL_H: &[&str] = &[
    "struct sysctllog {",
    "    unsigned int seen;",
    "};",
    "",
    "#define _SYSCTL_REGISTER(name) __link_set_add_text(sysctl_funcs, name);",
    "#define SYSCTL_SETUP(name, desc) \\",
    "    static void name(struct sysctllog **); \\",
    "    _SYSCTL_REGISTER(name); \\",
    "    static void name(struct sysctllog **clog)",
    "",
];

/// The value of the `switch-thunk` step after `rounds` rounds from `seed`, as the C computes it.
fn spin(seed: u32, rounds: u32) -> u32 {
    let mut x = seed;
    for i in 0..rounds {
        x = match x.wrapping_add(i) % 12 {
            0 => x.wrapping_add(3),
            1 => x ^ 0x55,
            2 => x.wrapping_mul(5),
            3 => x.wrapping_sub(7),
            4 => x << 2,
            5 => x >> 1,
            6 => x.wrapping_add(11),
            7 => !x,
            8 => x.wrapping_mul(9).wrapping_add(1),
            9 => x ^ 0xa5a5,
            10 => x.rotate_left(8),
            _ => x,
        };
    }
    x
}

fn shape_of(shape: &str) -> Shape {
    match shape {
        "zero-in-data" => Shape {
            after: "-fno-zero-initialized-in-bss in sys/conf/Makefile.kern.inc",
            top: lines(&[&[
                "extern char __bss_start[];",
                "",
                "unsigned int corpus_zero = 0u;",
                "static unsigned int corpus_static_zero = 0u;",
                "static struct {",
                "    unsigned int words[4];",
                "} corpus_zero_struct = {{0u}};",
                "unsigned int corpus_unset;",
                "static unsigned int corpus_static_unset;",
                "",
                "static unsigned int in_data(const void *p) {",
                "    return (unsigned long)p < (unsigned long)__bss_start;",
                "}",
            ]]),
            units: Vec::new(),
            checks: vec![
                ("in_data(&corpus_zero)", 1),
                ("in_data(&corpus_static_zero)", 1),
                ("in_data(&corpus_zero_struct)", 1),
                ("in_data(&corpus_unset)", 0),
                ("in_data(&corpus_static_unset)", 0),
                ("corpus_zero += 1u", 1),
                ("corpus_static_zero += 2u", 2),
                ("corpus_zero_struct.words[3] += 3u", 3),
                ("corpus_unset += 4u", 4),
                ("corpus_static_unset += 5u", 5),
            ],
        },
        "kernel-rcsid" => Shape {
            after: "__KERNEL_RCSID in sys/sys/cdefs_elf.h",
            top: lines(&[
                ELF_TYPES,
                SECTION_WALK,
                CDEFS,
                &[
                    "__KERNEL_COPYRIGHT(0, \"@(#) Copyright (c) 2026 The corpus. All rights reserved.\");",
                    "__KERNEL_RCSID(0, \"$NetBSD: corpus_main.c,v 1.1 2026/11/09 corpus Exp $\");",
                    "",
                    "unsigned int corpus_more(unsigned int);",
                ],
            ]),
            units: vec![(
                "more",
                lines(&[
                    CDEFS,
                    &[
                        "__KERNEL_RCSID(0, \"$NetBSD: corpus_more.c,v 1.2 2026/11/09 corpus Exp $\");",
                        "",
                        "unsigned int corpus_more(unsigned int x) {",
                        "    return x * 3u + 1u;",
                        "}",
                    ],
                ]),
            )],
            checks: vec![
                (
                    "section_of(\".ident\", \"$NetBSD: corpus_main.c,v 1.1 2026/11/09 corpus Exp $\")",
                    section(PROGBITS, MERGE_STRINGS),
                ),
                (
                    "section_of(\".ident\", \"$NetBSD: corpus_more.c,v 1.2 2026/11/09 corpus Exp $\")",
                    section(PROGBITS, MERGE_STRINGS),
                ),
                (
                    "section_of(\".copyright\", \"@(#) Copyright (c) 2026 The corpus.\")",
                    section(PROGBITS, MERGE_STRINGS),
                ),
                ("corpus_more(4u)", 13),
            ],
        },
        "module-set" => Shape {
            after: "MODULE in sys/sys/module.h and module_init in sys/kern/kern_module.c",
            top: lines(&[
                CDEFS,
                MODULE_H,
                &[
                    "/* Ensure that the kernel's link set isn't empty. */",
                    "static modinfo_t module_dummy;",
                    "__link_set_add_rodata(modules, module_dummy);",
                    "",
                    "MODULE(1, corpus_alpha, NULL);",
                    "",
                    "static int corpus_alpha_modcmd(modcmd_t cmd, void *arg) {",
                    "    *(unsigned int *)arg += 10u + (unsigned int)cmd;",
                    "    return 0;",
                    "}",
                    "",
                    "static unsigned int modules_walk(unsigned int what) {",
                    "    __link_set_decl(modules, modinfo_t);",
                    "    modinfo_t *const *mip;",
                    "    unsigned int out = 0;",
                    "    __link_set_foreach(mip, modules) {",
                    "        if ((*mip)->mi_modcmd == NULL) {",
                    "            out += what == 0u;",
                    "            continue;",
                    "        }",
                    "        if (what == 1u) {",
                    "            (*mip)->mi_modcmd(MODULE_CMD_INIT, &out);",
                    "        } else if (what == 2u) {",
                    "            out += (unsigned int)(*mip)->mi_class;",
                    "        } else if (what == 3u) {",
                    "            out += (*mip)->mi_required != NULL;",
                    "        } else if (what == 4u) {",
                    "            for (const char *c = (*mip)->mi_name; *c; c++) {",
                    "                out++;",
                    "            }",
                    "        }",
                    "    }",
                    "    return out;",
                    "}",
                    "",
                    "static unsigned int modules_count(void) {",
                    "    __link_set_decl(modules, modinfo_t);",
                    "    return (unsigned int)__link_set_count(modules);",
                    "}",
                ],
            ]),
            units: vec![(
                "more",
                lines(&[
                    CDEFS,
                    MODULE_H,
                    &[
                        "MODULE(2, corpus_beta, \"corpus_alpha\");",
                        "",
                        "static int corpus_beta_modcmd(modcmd_t cmd, void *arg) {",
                        "    *(unsigned int *)arg += 200u + (unsigned int)cmd;",
                        "    return 0;",
                        "}",
                    ],
                ]),
            )],
            checks: vec![
                ("modules_count()", 3),
                ("modules_walk(0u)", 1),
                ("modules_walk(1u)", 210),
                ("modules_walk(2u)", 3),
                ("modules_walk(3u)", 1),
                ("modules_walk(4u)", 23),
            ],
        },
        "sysctl-setup" => Shape {
            after: "SYSCTL_SETUP in sys/sys/sysctl.h and sysctl_init in sys/kern/kern_sysctl.c",
            top: lines(&[
                CDEFS,
                SYSCTL_H,
                &[
                    "typedef void sysctl_setup_func(struct sysctllog **);",
                    "__link_set_decl(sysctl_funcs, sysctl_setup_func);",
                    "",
                    "SYSCTL_SETUP(sysctl_corpus_a, \"corpus a\") {",
                    "    (*clog)->seen += 1u;",
                    "}",
                    "",
                    "SYSCTL_SETUP(sysctl_corpus_b, \"corpus b\") {",
                    "    (*clog)->seen += 20u;",
                    "}",
                    "",
                    "static unsigned int sysctl_run(void) {",
                    "    struct sysctllog log = {0u};",
                    "    struct sysctllog *clog = &log;",
                    "    sysctl_setup_func *const *sysctl_setup;",
                    "    __link_set_foreach(sysctl_setup, sysctl_funcs) {",
                    "        (**sysctl_setup)(&clog);",
                    "    }",
                    "    return log.seen;",
                    "}",
                ],
            ]),
            units: vec![(
                "more",
                lines(&[
                    CDEFS,
                    SYSCTL_H,
                    &[
                        "SYSCTL_SETUP(sysctl_corpus_c, \"corpus c\") {",
                        "    (*clog)->seen += 300u;",
                        "}",
                    ],
                ]),
            )],
            checks: vec![
                ("(unsigned int)__link_set_count(sysctl_funcs)", 3),
                ("sysctl_run()", 321),
            ],
        },
        "switch-thunk" => Shape {
            after: "-mcmodel=kernel and -mindirect-branch=thunk in sys/arch/amd64/conf/Makefile.amd64",
            top: lines(&[&[
                "static volatile unsigned int corpus_seed = 7u;",
                "",
                "static unsigned int corpus_pick(unsigned int k, unsigned int x) {",
                "    switch (k) {",
                "    case 0: return x + 3u;",
                "    case 1: return x ^ 0x55u;",
                "    case 2: return x * 5u;",
                "    case 3: return x - 7u;",
                "    case 4: return x << 2;",
                "    case 5: return x >> 1;",
                "    case 6: return x + 11u;",
                "    case 7: return ~x;",
                "    case 8: return x * 9u + 1u;",
                "    case 9: return x ^ 0xa5a5u;",
                "    case 10: return (x << 8) | (x >> 24);",
                "    default: return x;",
                "    }",
                "}",
                "",
                "static unsigned int corpus_spin(unsigned int rounds) {",
                "    unsigned int x = corpus_seed;",
                "    for (unsigned int i = 0; i < rounds; i++) {",
                "        x = corpus_pick((x + i) % 12u, x);",
                "    }",
                "    return x;",
                "}",
            ]]),
            units: Vec::new(),
            checks: vec![
                ("corpus_spin(1u)", i128::from(spin(7, 1))),
                ("corpus_spin(12u)", i128::from(spin(7, 12))),
                ("corpus_spin(64u)", i128::from(spin(7, 64))),
            ],
        },
        _ => unreachable!("no shape {shape}"),
    }
}

#[cfg(test)]
mod tests {
    use super::{SHAPES, shape_of, spin};
    use crate::{Options, generate};
    use corpus_model::Facet;

    #[test]
    fn every_shape_is_there_with_the_flag_line() {
        let manifest = generate(&Options::all()).unwrap();
        let cases: Vec<_> =
            manifest.cases.iter().filter(|case| case.facet == Facet::NetbsdKernel).collect();
        assert_eq!(cases.len(), SHAPES.len());
        for case in cases {
            assert!(case.has_tag("elf") && case.has_tag("x86-64"), "{}", case.id);
            assert!(
                case.flags.iter().any(|flag| flag == "-fno-zero-initialized-in-bss"),
                "{}",
                case.id
            );
        }
    }

    #[test]
    fn every_shape_prints_something() {
        for &shape in SHAPES {
            assert!(!shape_of(shape).checks.is_empty(), "{shape}");
        }
    }

    #[test]
    fn the_spin_walks_the_table() {
        assert_eq!(spin(7, 0), 7);
        // (7 + 0) % 12 is 7, so the first round is ~7.
        assert_eq!(spin(7, 1), !7u32);
    }
}
