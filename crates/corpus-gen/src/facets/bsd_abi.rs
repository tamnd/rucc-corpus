//! The parts of the FreeBSD ABI that live in the object file: symbol versions, ifuncs, and the calling convention of the boot code.
//!
//! `symbol-versions` is how FreeBSD's libraries keep old entry points.
//! `__sym_compat` from `sys/sys/cdefs.h` gives a function a hidden version with `.symver impl, sym@VER`, and `__sym_default` gives the default with `sym@@@VER`.
//! GCC's `symver` attribute does the same from C, and the libraries also version aliases made with `__strong_reference` and `__weak_reference`.
//! Each case calls the default version by its plain name and then reads its own `.symtab`, so a directive that the compiler drops or changes is a wrong answer.
//! The cases are executables, where the linker keeps a hidden version as a local symbol and the default version as a global one.
//!
//! `ifunc-static` is the resolvers of `DEFINE_UIFUNC` from `sys/x86/include/ifunc.h`, as FreeBSD's `libc` uses them for `memcpy` and its family.
//! In a static program the linker puts an `R_X86_64_IRELATIVE` relocation between `__rela_iplt_start` and `__rela_iplt_end`, and the start up code runs each resolver before the constructors and `main`.
//! In a dynamic program the run time linker does it.
//! Each case runs both ways, calls the function and takes its address, and checks that the resolver ran and that the symbol is an `STT_GNU_IFUNC`.
//!
//! `boot-abi` is the flag line of `stand/i386/boot2`, where `-mrtd` and `-mregparm=3` are the defaults.
//! The boot code calls assembly that assumes them, and assembly calls C that must keep them.
//! A variadic function stays caller pops, and `cdecl` with `regparm(0)` gives the old convention back.
//! The cases are 32-bit programs with their own `_start` and no C library, so they need no 32-bit `libc` and run on any x86-64 Linux.
//! Each prints its result and how far the stack pointer moved, which must be zero.
//!
//! All of these need an ELF target and x86 code, so every case carries the `elf` and `x86-64` tags.

use crate::Sink;
use crate::emit::Program;
use crate::facets::bsd_asm::{ELF_TYPES, READER_OFF};
use crate::lang::Ty;
use corpus_model::{Axes, Case, Dialect, Expect, Facet, Unit};

/// The tags of every case.
const TAGS: &[&str] = &["gnu", "elf", "x86-64", "provenance:freebsd"];

/// The shapes of `symbol-versions`.
const VERSIONS: &[&str] = &[
    "sym-compat",
    "sym-compat-reader-off",
    "symver-attribute",
    "symver-units",
    "versioned-alias",
    "weak-version",
];

/// The shapes of `ifunc-static`.
const IFUNCS: &[&str] =
    &["call", "address", "units", "resolver-before-constructors", "memcpy-family"];

/// How an `ifunc-static` case is linked.
const LINKS: &[&str] = &["static", "dynamic"];

/// The shapes of `boot-abi`.
const BOOT: &[&str] = &[
    "asm-callee-registers",
    "asm-callee-pops",
    "wide-argument",
    "asm-caller",
    "varargs",
    "cdecl-override",
];

/// The flag line of `stand/i386/boot2/Makefile` in FreeBSD 15.1, with no PIE and no C library.
///
/// The case pins `-Os`, as the boot code does, so the level of the run does not change it.
pub(crate) const BOOT_FLAGS: &[&str] = &[
    "-m32",
    "-march=i386",
    "-ffreestanding",
    "-mrtd",
    "-mregparm=3",
    "-fomit-frame-pointer",
    "-mno-mmx",
    "-mno-sse",
    "-fno-pie",
    "-no-pie",
    "-nostdlib",
    "-static",
    "-Os",
];

/// The `.symtab` value of a local function, `100 + 10 * STB_LOCAL + STT_FUNC`.
const LOCAL_FUNC: i128 = 102;
/// A global function.
const GLOBAL_FUNC: i128 = 112;
/// A global `STT_GNU_IFUNC`.
const GLOBAL_IFUNC: i128 = 120;

/// Emits every case of the three facets.
pub(crate) fn generate(sink: &mut Sink<'_>) {
    for &shape in VERSIONS {
        if !sink.wants(Facet::SymbolVersions) {
            break;
        }
        sink.push_case(version(shape));
    }
    for &shape in IFUNCS {
        for &link in LINKS {
            if !sink.wants(Facet::IfuncStatic) {
                break;
            }
            sink.push_case(ifunc(shape, link));
        }
    }
    for &shape in BOOT {
        if !sink.wants(Facet::BootAbi) {
            break;
        }
        sink.push_case(boot(shape));
    }
}

/// Owned lines from string slices.
fn lines(parts: &[&[&str]]) -> Vec<String> {
    parts.concat().iter().map(|line| (*line).to_owned()).collect()
}

/// A unit of a case, with the header every generated file has.
fn unit(name: &str, shape: &str, text: &[&str]) -> Unit {
    let mut out = format!(
        "// The {name} unit of the {shape} case.\n// Generated by rucc-corpus. Edit the generator, not this file.\n\n"
    );
    for line in text {
        out.push_str(line);
        out.push('\n');
    }
    Unit::new(name, out)
}

/// A case of one facet from its parts.
fn case(
    facet: Facet,
    axes: Axes,
    (source, expected): (String, String),
    units: Vec<Unit>,
    flags: &[&str],
) -> Case {
    Case::linked(
        facet,
        axes,
        Dialect::C17,
        source,
        units,
        flags.iter().map(|flag| (*flag).to_owned()).collect(),
        Expect::Output(expected),
    )
    .tagged(TAGS)
}

/// A walk over the program's own `.symtab`, read from `/proc/self/exe`.
///
/// `kind` gives zero for a name that is not there and `100 + 10 * binding + type` for one that is.
/// `same` says whether two names have the same value.
const SYMBOL_WALK: &[&str] = &[
    "int open(const char *, int, ...);",
    "long read(int, void *, unsigned long);",
    "int close(int);",
    "",
    "typedef struct {",
    "    unsigned int name;",
    "    unsigned char info, other;",
    "    unsigned short shndx;",
    "    unsigned long value, size;",
    "} elf_sym;",
    "",
    "#define FILE_BYTES (1ul << 23)",
    "static unsigned char file[FILE_BYTES];",
    "static long file_size;",
    "",
    "static const elf_sym *symbol(const char *name) {",
    "    if (file_size == 0) {",
    "        int fd = open(\"/proc/self/exe\", 0);",
    "        long got;",
    "        while (fd >= 0 && (got = read(fd, file + file_size, FILE_BYTES - (unsigned long)file_size)) > 0) {",
    "            file_size += got;",
    "        }",
    "        if (fd >= 0) {",
    "            close(fd);",
    "        }",
    "    }",
    "    const elf_ehdr *eh = (const elf_ehdr *)file;",
    "    if (file_size < 64 || eh->shoff == 0u) {",
    "        return 0;",
    "    }",
    "    const elf_shdr *sh = (const elf_shdr *)(file + eh->shoff);",
    "    for (int i = 0; i < eh->shnum; i++) {",
    "        if (sh[i].type != 2u) {",
    "            continue;",
    "        }",
    "        const char *names = (const char *)file + sh[sh[i].link].offset;",
    "        const elf_sym *sym = (const elf_sym *)(file + sh[i].offset);",
    "        unsigned long count = sh[i].size / sh[i].entsize;",
    "        for (unsigned long s = 0; s < count; s++) {",
    "            const char *n = names + sym[s].name;",
    "            int k = 0;",
    "            while (name[k] && n[k] == name[k]) {",
    "                k++;",
    "            }",
    "            if (!name[k] && !n[k]) {",
    "                return &sym[s];",
    "            }",
    "        }",
    "    }",
    "    return 0;",
    "}",
    "",
    "static unsigned int kind(const char *name) {",
    "    const elf_sym *s = symbol(name);",
    "    return s ? 100u + 10u * (unsigned int)(s->info >> 4) + (unsigned int)(s->info & 15u) : 0u;",
    "}",
    "",
    "static unsigned int same(const char *a, const char *b) {",
    "    const elf_sym *x = symbol(a);",
    "    const elf_sym *y = symbol(b);",
    "    return x && y && x->value == y->value;",
    "}",
    "",
];

/// The macros of FreeBSD's `sys/sys/cdefs.h` that version and alias a symbol.
const CDEFS: &[&str] = &[
    "#define __sym_compat(sym, impl, verid) __asm__(\".symver \" #impl \", \" #sym \"@\" #verid)",
    "#define __sym_default(sym, impl, verid) __asm__(\".symver \" #impl \", \" #sym \"@@@\" #verid)",
    "#define __strong_reference(sym, aliassym) \\",
    "    extern __typeof(sym) aliassym __attribute__((__alias__(#sym)))",
    "#define __weak_reference(sym, alias) \\",
    "    __asm__(\".weak \" #alias); \\",
    "    __asm__(\".equ \" #alias \", \" #sym)",
    "",
];

/// An old and a new `corpus_f`, as `lib/libc/gen/fts-compat11.c` keeps the old `fts_open`.
const COMPAT_F: &[&str] = &[
    "__attribute__((noinline)) int corpus_f_old(int x) {",
    "    return x + 1;",
    "}",
    "",
    "__attribute__((noinline)) int corpus_f_new(int x) {",
    "    return x * 3;",
    "}",
    "",
    "__sym_compat(corpus_f, corpus_f_old, FBSD_1.0);",
    "__sym_default(corpus_f, corpus_f_new, FBSD_1.7);",
    "",
];

/// The case of a `symbol-versions` shape.
fn version(shape: &str) -> Case {
    let mut program = Program::new(format!("{shape} after the __sym_compat lines of FreeBSD 15.1"));
    for line in lines(&[ELF_TYPES, SYMBOL_WALK, CDEFS]) {
        program.top(line);
    }
    let mut units = Vec::new();
    let mut flags: &[&str] = &[];
    match shape {
        "sym-compat" | "sym-compat-reader-off" | "symver-units" => {
            if shape == "symver-units" {
                units.push(unit("compat", shape, &[CDEFS, COMPAT_F].concat()));
            } else {
                for line in lines(&[COMPAT_F]) {
                    program.top(line);
                }
            }
            if shape == "sym-compat-reader-off" {
                flags = &[READER_OFF];
            }
            program.top("int corpus_f(int);");
            program.check(Ty::U32, "corpus_f(14)", 42);
            program.check(Ty::U32, "kind(\"corpus_f@FBSD_1.0\")", LOCAL_FUNC);
            program.check(Ty::U32, "kind(\"corpus_f@@FBSD_1.7\")", GLOBAL_FUNC);
            program.check(Ty::U32, "kind(\"corpus_f_old\")", GLOBAL_FUNC);
            program.check(Ty::U32, "same(\"corpus_f@FBSD_1.0\", \"corpus_f_old\")", 1);
        }
        "symver-attribute" => {
            for line in [
                "__attribute__((symver(\"corpus_g@FBSD_1.0\"))) int corpus_g_old(int x) {",
                "    return x - 5;",
                "}",
                "",
                "__attribute__((symver(\"corpus_g@@FBSD_1.1\"))) int corpus_g_new(int x) {",
                "    return x ^ 6;",
                "}",
                "",
                "int corpus_g(int);",
            ] {
                program.top(line);
            }
            program.check(Ty::U32, "corpus_g(14)", 8);
            program.check(Ty::U32, "kind(\"corpus_g@FBSD_1.0\")", LOCAL_FUNC);
            program.check(Ty::U32, "kind(\"corpus_g@@FBSD_1.1\")", GLOBAL_FUNC);
            program.check(Ty::U32, "same(\"corpus_g@@FBSD_1.1\", \"corpus_g_new\")", 1);
        }
        "versioned-alias" => {
            for line in [
                "__attribute__((noinline)) int corpus_h_impl(int x) {",
                "    return x * 5;",
                "}",
                "",
                "__strong_reference(corpus_h_impl, corpus_h_compat);",
                "__sym_compat(corpus_h, corpus_h_compat, FBSD_1.0);",
                "__sym_default(corpus_h, corpus_h_impl, FBSD_1.2);",
                "int corpus_h(int);",
            ] {
                program.top(line);
            }
            program.check(Ty::U32, "corpus_h(3)", 15);
            program.check(Ty::U32, "kind(\"corpus_h@FBSD_1.0\")", LOCAL_FUNC);
            program.check(Ty::U32, "kind(\"corpus_h@@FBSD_1.2\")", GLOBAL_FUNC);
            program.check(Ty::U32, "same(\"corpus_h@FBSD_1.0\", \"corpus_h@@FBSD_1.2\")", 1);
        }
        "weak-version" => {
            for line in [
                "__attribute__((noinline)) int corpus_k_impl(int x) {",
                "    return x + 100;",
                "}",
                "",
                "__weak_reference(corpus_k_impl, corpus_k_weak);",
                "__sym_compat(corpus_k, corpus_k_weak, FBSD_1.0);",
                "__sym_default(corpus_k, corpus_k_impl, FBSD_1.4);",
                "int corpus_k(int);",
            ] {
                program.top(line);
            }
            program.check(Ty::U32, "corpus_k(11)", 111);
            program.check(Ty::U32, "kind(\"corpus_k@FBSD_1.0\")", LOCAL_FUNC);
            program.check(Ty::U32, "kind(\"corpus_k@@FBSD_1.4\")", GLOBAL_FUNC);
            program.check(Ty::U32, "same(\"corpus_k@FBSD_1.0\", \"corpus_k@@FBSD_1.4\")", 1);
        }
        _ => unreachable!("{shape}"),
    }
    case(Facet::SymbolVersions, Axes::of([("shape", shape)]), program.finish(), units, flags)
}

/// FreeBSD's `DEFINE_UIFUNC` from `sys/x86/include/ifunc.h`.
const IFUNC_H: &[&str] = &[
    "#define __used __attribute__((__used__))",
    "#define __unused __attribute__((__unused__))",
    "#define DEFINE_UIFUNC(qual, ret_type, name, args) \\",
    "    static ret_type (*name##_resolver(unsigned int, unsigned int, unsigned int, unsigned int))args __used; \\",
    "    qual ret_type name args __attribute__((ifunc(#name \"_resolver\"))); \\",
    "    static ret_type (*name##_resolver( \\",
    "        unsigned int cpu_feature __unused, \\",
    "        unsigned int cpu_feature2 __unused, \\",
    "        unsigned int cpu_stdext_feature __unused, \\",
    "        unsigned int cpu_stdext_feature2 __unused))args",
    "",
];

/// The `IRELATIVE` relocations of a static program, as `lib/csu/common/reloc.c` walks them.
const IPLT_WALK: &[&str] = &[
    "typedef struct {",
    "    unsigned long offset, info;",
    "    long addend;",
    "} elf_rela;",
    "",
    "extern const elf_rela __rela_iplt_start[] __attribute__((weak));",
    "extern const elf_rela __rela_iplt_end[] __attribute__((weak));",
    "",
    "static unsigned int irelative(void) {",
    "    unsigned int n = 0;",
    "    for (const elf_rela *r = __rela_iplt_start; r < __rela_iplt_end; r++) {",
    "        n += (r->info & 0xffffffffu) == 37u;",
    "    }",
    "    return n;",
    "}",
    "",
    "static unsigned int all_irelative(void) {",
    "    return irelative() == (unsigned int)(__rela_iplt_end - __rela_iplt_start);",
    "}",
    "",
];

/// A `memcpy` with two bodies and a resolver that picks one, as `lib/libc/amd64/string` does.
const MEMCPY: &[&str] = &[
    "unsigned int corpus_resolved;",
    "static volatile unsigned int corpus_level = 2u;",
    "",
    "static void *copy_bytes(void *d, const void *s, unsigned long n) {",
    "    unsigned char *a = d;",
    "    const unsigned char *b = s;",
    "    while (n--) {",
    "        *a++ = *b++;",
    "    }",
    "    return d;",
    "}",
    "",
    "static void *copy_backward(void *d, const void *s, unsigned long n) {",
    "    unsigned char *a = d;",
    "    const unsigned char *b = s;",
    "    while (n) {",
    "        n--;",
    "        a[n] = b[n];",
    "    }",
    "    return d;",
    "}",
    "",
    "DEFINE_UIFUNC(, void *, corpus_memcpy, (void *, const void *, unsigned long)) {",
    "    corpus_resolved++;",
    "    return corpus_level >= 2u ? copy_backward : copy_bytes;",
    "}",
    "",
];

/// The rest of the family, each with its own resolver.
const FAMILY: &[&str] = &[
    "static void *set_bytes(void *d, int c, unsigned long n) {",
    "    unsigned char *a = d;",
    "    while (n--) {",
    "        *a++ = (unsigned char)c;",
    "    }",
    "    return d;",
    "}",
    "",
    "static void *move_bytes(void *d, const void *s, unsigned long n) {",
    "    unsigned char *a = d;",
    "    const unsigned char *b = s;",
    "    if (a < b) {",
    "        while (n--) {",
    "            *a++ = *b++;",
    "        }",
    "    } else {",
    "        while (n) {",
    "            n--;",
    "            a[n] = b[n];",
    "        }",
    "    }",
    "    return d;",
    "}",
    "",
    "static unsigned long length(const char *s) {",
    "    unsigned long n = 0;",
    "    while (s[n]) {",
    "        n++;",
    "    }",
    "    return n;",
    "}",
    "",
    "DEFINE_UIFUNC(, void *, corpus_memset, (void *, int, unsigned long)) {",
    "    corpus_resolved++;",
    "    return set_bytes;",
    "}",
    "",
    "DEFINE_UIFUNC(, void *, corpus_memmove, (void *, const void *, unsigned long)) {",
    "    corpus_resolved++;",
    "    return move_bytes;",
    "}",
    "",
    "DEFINE_UIFUNC(, unsigned long, corpus_strlen, (const char *)) {",
    "    corpus_resolved++;",
    "    return length;",
    "}",
    "",
];

/// What `main` copies and how it sums the copy.
const COPY: &[&str] = &[
    "static unsigned char corpus_src[37];",
    "static unsigned char corpus_dst[37];",
    "",
    "static unsigned int copy_sum(void *(*copy)(void *, const void *, unsigned long)) {",
    "    unsigned int sum = 0;",
    "    for (int i = 0; i < 37; i++) {",
    "        corpus_src[i] = (unsigned char)(i * 7 + 1);",
    "        corpus_dst[i] = 0;",
    "    }",
    "    copy(corpus_dst, corpus_src, 37);",
    "    for (int i = 0; i < 37; i++) {",
    "        sum = sum * 31u + corpus_dst[i];",
    "    }",
    "    return sum;",
    "}",
    "",
];

/// The sum that `copy_sum` prints.
fn copy_sum() -> i128 {
    let mut sum = 0u32;
    for i in 0..37u32 {
        sum = sum.wrapping_mul(31).wrapping_add((i * 7 + 1) & 0xff);
    }
    i128::from(sum)
}

/// The case of an `ifunc-static` shape, linked one way.
fn ifunc(shape: &str, link: &str) -> Case {
    let mut program =
        Program::new(format!("{shape} after DEFINE_UIFUNC in FreeBSD 15.1, linked {link}"));
    let mut top = lines(&[ELF_TYPES, SYMBOL_WALK, IFUNC_H, IPLT_WALK]);
    let mut units = Vec::new();
    if shape == "units" {
        units.push(unit("resolver", shape, &[IFUNC_H, MEMCPY].concat()));
        top.extend(lines(&[&[
            "extern unsigned int corpus_resolved;",
            "void *corpus_memcpy(void *, const void *, unsigned long);",
            "",
        ]]));
    } else {
        top.extend(lines(&[MEMCPY]));
    }
    top.extend(lines(&[COPY]));
    let sum = copy_sum();
    match shape {
        "call" | "units" => {
            program.check(Ty::U32, "copy_sum(corpus_memcpy)", sum);
        }
        "address" => {
            top.extend(lines(&[&[
                "void *(*const corpus_table[])(void *, const void *, unsigned long) = {",
                "    corpus_memcpy,",
                "};",
                "",
            ]]));
            program.check(Ty::U32, "corpus_table[0] == corpus_memcpy", 1);
            program.check(Ty::U32, "copy_sum(corpus_table[0])", sum);
        }
        "resolver-before-constructors" => {
            top.extend(lines(&[&[
                "static unsigned int seen_in_constructor;",
                "static unsigned int sum_in_constructor;",
                "",
                "__attribute__((constructor)) static void early(void) {",
                "    seen_in_constructor = corpus_resolved;",
                "    sum_in_constructor = copy_sum(corpus_memcpy);",
                "}",
                "",
            ]]));
            program.check(Ty::U32, "seen_in_constructor != 0u", 1);
            program.check(Ty::U32, "sum_in_constructor", sum);
        }
        "memcpy-family" => {
            top.extend(lines(&[FAMILY]));
            top.extend(lines(&[&["static char corpus_text[32] = \"0123456789abcdef\";", ""]]));
            program.line("corpus_memmove(corpus_text + 2, corpus_text, 10);");
            program.line("corpus_memset(corpus_text + 12, 'z', 3);");
            program.check(Ty::U32, "copy_sum(corpus_memcpy)", sum);
            program.check(Ty::U32, "corpus_strlen(corpus_text)", 16);
            program.check(
                Ty::U32,
                "(unsigned int)corpus_text[2] * 1000u + (unsigned int)corpus_text[11] * 10u + (corpus_text[14] == 'z')",
                i128::from(b'0') * 1000 + i128::from(b'9') * 10 + 1,
            );
            program.check(Ty::U32, "kind(\"corpus_strlen\")", GLOBAL_IFUNC);
        }
        _ => unreachable!("{shape}"),
    }
    for line in top {
        program.top(line);
    }
    program.check(Ty::U32, "corpus_resolved != 0u", 1);
    program.check(Ty::U32, "kind(\"corpus_memcpy\")", GLOBAL_IFUNC);
    let flags: &[&str] = if link == "static" {
        program.check(Ty::U32, "irelative() != 0u", 1);
        program.check(Ty::U32, "all_irelative()", 1);
        &["-static"]
    } else {
        &[]
    };
    case(
        Facet::IfuncStatic,
        Axes::of([("shape", shape), ("link", link)]),
        program.finish(),
        units,
        flags,
    )
}

