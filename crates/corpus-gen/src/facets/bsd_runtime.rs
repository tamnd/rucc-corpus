//! What the BSD C runtime does at run time: thread local storage, the unwinder, and the size of boot code.
//!
//! `tls-models` is the four TLS access models, as `ld.elf_so` on NetBSD and `rtld` on FreeBSD serve them.
//! Local exec and initial exec are the models of the executable, and each case is linked both dynamic and static.
//! In the initial exec case the variables live in another unit, so the access goes through the GOT.
//! Global dynamic and local dynamic are the models of a module, so those cases put the variables in a module that the program opens with `dlopen`, and every access calls `__tls_get_addr`.
//! Each case runs the same work in two threads and in `main`, and checks that each thread has its own copy, that a 64 byte aligned variable is aligned in every thread, and that the initial values hold.
//!
//! `unwinder` is the walk that `_Unwind_Backtrace` does over the frames of the program, and the forced unwind that `pthread_exit` and `pthread_cancel` do.
//! A backtrace case calls the unwinder three frames deep and finds each caller in order.
//! The frames have `alloca`, a realigned local, callee saved registers in use, or a signal handler between the unwinder and the caller.
//! A cleanup case ends a thread three frames deep, and each frame has a variable with the `cleanup` attribute, which must run in order.
//!
//! `boot-sizes` is code in the shape of the BSD boot blocks, built with the flag line of FreeBSD's `boot2` and measured.
//! FreeBSD's `boot2` must fit in 7.5 KB, and NetBSD's `bootxx` and `dosboot` have limits of the same kind.
//! The shapes are `fsread` and `lookup` after `stand/libsa/ufsread.c`, a small `printf` after `stand/libsa/printf.c`, and the argument parser of `stand/i386/boot2/boot2.c`.
//! Each case puts that code in a section of its own, prints what it computed, and prints whether the section is within its budget.
//! The budget is the size from GCC 13, GCC 15 or Clang 18, whichever is largest, plus a quarter, so a compiler that makes boot code much larger fails the case.
//!
//! All of these need an ELF target and x86 code, so every case carries the `elf` and `x86-64` tags.

use crate::Sink;
use crate::emit::Program;
use crate::facets::bsd_abi::{BOOT_FLAGS, BOOT_IO};
use crate::lang::Ty;
use corpus_model::{Axes, Case, Dialect, Expect, Facet, Unit};

/// The tags of every `tls-models` and `unwinder` case.
const TAGS: &[&str] = &["gnu", "elf", "x86-64", "provenance:netbsd"];

/// The tags of every `boot-sizes` case.
const BOOT_TAGS: &[&str] = &["gnu", "elf", "x86-64", "provenance:freebsd"];

/// The models of `tls-models`, with the ways each one is linked.
const MODELS: &[(&str, &[&str])] = &[
    ("local-exec", &["dynamic", "static"]),
    ("initial-exec", &["dynamic", "static"]),
    ("global-dynamic", &["dlopen"]),
    ("local-dynamic", &["dlopen"]),
];

/// The shapes of `unwinder`.
const UNWINDS: &[&str] =
    &["plain", "alloca", "realign", "callee-saved", "signal", "cleanup-exit", "cleanup-cancel"];

/// The shapes of `boot-sizes`.
const SIZES: &[&str] = &["fsread", "lookup", "printf", "parse"];

/// The seeds of the two threads and of `main` in a `tls-models` case.
const TLS_SEEDS: [u32; 3] = [3, 11, 6];

/// The seed of a backtrace case.
const UNWIND_SEED: u32 = 3;

/// The value a cleanup case passes to its thread.
const CLEANUP_ARG: u32 = 40;

/// Emits every case of the three facets.
pub(crate) fn generate(sink: &mut Sink<'_>) {
    for &(model, links) in MODELS {
        for &link in links {
            if !sink.wants(Facet::TlsModels) {
                break;
            }
            sink.push_case(tls(model, link));
        }
    }
    for &shape in UNWINDS {
        if !sink.wants(Facet::Unwinder) {
            break;
        }
        sink.push_case(unwind(shape));
    }
    for &shape in SIZES {
        if !sink.wants(Facet::BootSizes) {
            break;
        }
        sink.push_case(size(shape));
    }
}

/// A case of one facet from its parts.
fn case(
    facet: Facet,
    axes: Axes,
    (source, expected): (String, String),
    units: Vec<Unit>,
    flags: &[&str],
    tags: &[&str],
) -> Case {
    Case::linked(
        facet,
        axes,
        Dialect::C17,
        source,
        units,
        flags.iter().map(|flag| (*flag).to_owned()).collect(),
        Expect::Output(expected),
    )
    .tagged(tags)
}

/// A unit of a case from its text, with the header every generated file has.
fn unit_text(purpose: &str, body: &str) -> String {
    format!(
        "// {purpose}\n// Generated by rucc-corpus. Edit the generator, not this file.\n\n{body}"
    )
}

/// The thread local variables of a `tls-models` case, written with a storage class and a model.
fn tls_variables(storage: &str, model: &str) -> String {
    let attr = if model.is_empty() {
        String::new()
    } else {
        format!(" __attribute__((tls_model(\"{model}\")))")
    };
    format!(
        "{storage}_Thread_local unsigned int tls_a{attr} = 7u;\n\
         {storage}_Thread_local unsigned int tls_b[4]{attr} = {{1u, 2u, 3u, 4u}};\n\
         {storage}_Thread_local unsigned int tls_zero{attr};\n\
         {storage}_Thread_local unsigned char tls_big[64]{attr} __attribute__((aligned(64)));\n"
    )
}

/// The functions that use the thread local variables, which the program reaches through pointers.
const TLS_ACCESS: &str = "\
__attribute__((noinline)) unsigned int corpus_work(unsigned int seed) {
    for (unsigned int i = 0; i < 100u; i++) {
        tls_a += seed + i;
        tls_b[i & 3u] ^= i * seed;
        tls_big[i & 63u] += (unsigned char)i;
        tls_zero += tls_big[(i * 7u) & 63u];
    }
    return tls_a * 3u + tls_b[0] + tls_b[1] + tls_b[2] + tls_b[3] + tls_zero;
}

unsigned long corpus_addr(void) {
    return (unsigned long)&tls_a;
}

unsigned int corpus_aligned(void) {
    return ((unsigned long)tls_big & 63u) == 0u;
}

unsigned int corpus_a(void) {
    return tls_a;
}

unsigned int corpus_rest(void) {
    return tls_b[0] + tls_b[1] + tls_b[2] + tls_b[3] + tls_zero;
}
";

/// The threads of a `tls-models` case.
const TLS_THREADS: &[&str] = &[
    "struct corpus_slot {",
    "    unsigned int seed, value, aligned;",
    "    unsigned long addr;",
    "};",
    "",
    "static unsigned int (*p_work)(unsigned int);",
    "static unsigned long (*p_addr)(void);",
    "static unsigned int (*p_aligned)(void);",
    "static unsigned int (*p_a)(void);",
    "static unsigned int (*p_rest)(void);",
    "",
    "static void *thread_main(void *arg) {",
    "    struct corpus_slot *s = arg;",
    "    s->value = p_work(s->seed);",
    "    s->addr = p_addr();",
    "    s->aligned = p_aligned();",
    "    return 0;",
    "}",
];

/// What `corpus_work` returns on a fresh thread, worked out the way a correct build works it out.
fn tls_work(seed: u32) -> u32 {
    let mut a: u32 = 7;
    let mut b: [u32; 4] = [1, 2, 3, 4];
    let mut zero: u32 = 0;
    let mut big = [0u8; 64];
    for i in 0..100u32 {
        a = a.wrapping_add(seed).wrapping_add(i);
        b[(i & 3) as usize] ^= i.wrapping_mul(seed);
        let at = (i & 63) as usize;
        big[at] = big[at].wrapping_add(i as u8);
        zero = zero.wrapping_add(u32::from(big[(i.wrapping_mul(7) & 63) as usize]));
    }
    a.wrapping_mul(3)
        .wrapping_add(b.iter().fold(0u32, |sum, v| sum.wrapping_add(*v)))
        .wrapping_add(zero)
}

/// The case of one TLS model, linked one way.
fn tls(model: &str, link: &str) -> Case {
    let mut program = Program::new(format!(
        "{model} thread local storage, linked {link}, after the TLS of NetBSD's ld.elf_so"
    ));
    program.define("_POSIX_C_SOURCE", "200809L");
    program.include("pthread.h");
    let mut units = Vec::new();
    let mut tags = TAGS.to_vec();
    tags.push("threads");
    tags.push("headers");
    match model {
        "local-exec" => {
            program.top(tls_variables("static ", model));
            program.top(TLS_ACCESS);
        }
        "initial-exec" => {
            units.push(Unit::new(
                "tlsdata",
                unit_text(
                    "The thread local variables of the initial-exec case.",
                    &tls_variables("", ""),
                ),
            ));
            program.top(
                tls_variables("extern ", model)
                    .replace(" = 7u", "")
                    .replace(" = {1u, 2u, 3u, 4u}", ""),
            );
            program.top(TLS_ACCESS);
        }
        "global-dynamic" | "local-dynamic" => {
            let storage = if model == "local-dynamic" { "static " } else { "" };
            units.push(Unit::module(
                "tlsdata",
                unit_text(
                    &format!("The thread local variables of the {model} case and the functions that use them."),
                    &format!("{}\n{TLS_ACCESS}", tls_variables(storage, model)),
                ),
            ));
            program.include("dlfcn.h");
            tags.push("dlopen");
        }
        _ => unreachable!("{model}"),
    }
    for line in TLS_THREADS {
        program.top(*line);
    }
    if link == "dlopen" {
        program.line("void *handle = dlopen(\"./tlsdata.so\", RTLD_NOW);");
        program.line("if (!handle) {");
        program.line_at(1, "return 1;");
        program.line("}");
        for name in ["work", "addr", "aligned", "a", "rest"] {
            program.line(format!("*(void **)&p_{name} = dlsym(handle, \"corpus_{name}\");"));
        }
    } else {
        for name in ["work", "addr", "aligned", "a", "rest"] {
            program.line(format!("p_{name} = corpus_{name};"));
        }
    }
    program.line(format!(
        "struct corpus_slot slots[2] = {{{{{}u, 0u, 0u, 0ul}}, {{{}u, 0u, 0u, 0ul}}}};",
        TLS_SEEDS[0], TLS_SEEDS[1]
    ));
    program.line("pthread_t threads[2];");
    program.line("for (int i = 0; i < 2; i++) {");
    program.line_at(1, "pthread_create(&threads[i], 0, thread_main, &slots[i]);");
    program.line("}");
    program.line("for (int i = 0; i < 2; i++) {");
    program.line_at(1, "pthread_join(threads[i], 0);");
    program.line("}");
    program.check(Ty::U32, "slots[0].value", i128::from(tls_work(TLS_SEEDS[0])));
    program.check(Ty::U32, "slots[1].value", i128::from(tls_work(TLS_SEEDS[1])));
    program.check(Ty::U32, "p_a()", 7);
    program.check(Ty::U32, "p_rest()", 10);
    program.check(
        Ty::U32,
        "slots[0].addr != slots[1].addr && slots[0].addr != p_addr() && slots[1].addr != p_addr()",
        1,
    );
    program.check(Ty::U32, "slots[0].aligned + slots[1].aligned + p_aligned()", 3);
    program.check(
        Ty::U32,
        &format!("p_work({}u)", TLS_SEEDS[2]),
        i128::from(tls_work(TLS_SEEDS[2])),
    );
    let flags: &[&str] = if link == "static" { &["-pthread", "-static"] } else { &["-pthread"] };
    case(
        Facet::TlsModels,
        Axes::of([("model", model), ("link", link)]),
        program.finish(),
        units,
        flags,
        &tags,
    )
}

/// The unwinder entry points, declared here so the case needs no `unwind.h`.
const UNWIND_DECLS: &[&str] = &[
    "struct _Unwind_Context;",
    "int _Unwind_Backtrace(int (*)(struct _Unwind_Context *, void *), void *);",
    "unsigned long _Unwind_GetIP(struct _Unwind_Context *);",
    "void *_Unwind_FindEnclosingFunction(void *);",
    "",
    "#define FRAMES 64",
    "static void *frames[FRAMES];",
    "static unsigned int depth;",
    "static volatile unsigned int seed = 3u;",
    "",
    "static int note(struct _Unwind_Context *context, void *unused) {",
    "    (void)unused;",
    "    if (depth < FRAMES) {",
    "        frames[depth++] = _Unwind_FindEnclosingFunction((void *)(_Unwind_GetIP(context) - 1u));",
    "    }",
    "    return 0;",
    "}",
    "",
    "__attribute__((noinline)) static unsigned int probe(void) {",
    "    depth = 0u;",
    "    _Unwind_Backtrace(note, 0);",
    "    return depth;",
    "}",
    "",
    "/* The index of the first frame at or after from that is in fn, or FRAMES. */",
    "static unsigned int find(void *fn, unsigned int from) {",
    "    for (unsigned int i = from; i < depth; i++) {",
    "        if (frames[i] == fn) {",
    "            return i;",
    "        }",
    "    }",
    "    return FRAMES;",
    "}",
    "",
];

/// The body of the innermost frame of a backtrace case, which sets `r`.
fn unwind_body(shape: &str) -> &'static [&'static str] {
    match shape {
        "plain" => &["    unsigned int r = (probe() != 0u) + x;"],
        "alloca" => &[
            "    char *p = __builtin_alloca(x * 16u + 8u);",
            "    p[x] = (char)x;",
            "    unsigned int r = (probe() != 0u) + (unsigned int)p[x];",
        ],
        "realign" => &[
            "    volatile unsigned int wide[8] __attribute__((aligned(64)));",
            "    wide[x & 7u] = x;",
            "    unsigned int r = (probe() != 0u) + wide[x & 7u] + (((unsigned long)wide & 63u) != 0u);",
        ],
        "callee-saved" => &[
            "    unsigned int a = x * 3u, b = x * 5u, c = x * 7u;",
            "    __asm__ volatile(\"\" : \"+r\"(a), \"+r\"(b), \"+r\"(c) : : \"rbx\", \"r12\", \"r13\", \"r14\", \"r15\");",
            "    unsigned int r = (probe() != 0u) + a + b + c;",
        ],
        "signal" => &["    raise(SIGUSR1);", "    unsigned int r = x;"],
        _ => unreachable!("{shape}"),
    }
}

/// What a backtrace case's chain of calls returns, worked out the way a correct build works it out.
fn unwind_result(shape: &str) -> u32 {
    let x = UNWIND_SEED + 2;
    let r = match shape {
        "plain" | "alloca" | "realign" => 1 + x,
        "callee-saved" => 1 + x * 3 + x * 5 + x * 7,
        "signal" => x,
        _ => unreachable!("{shape}"),
    };
    let f3 = r * 2 + 1;
    let f2 = f3 * 3 + UNWIND_SEED + 1;
    f2 * 5 + UNWIND_SEED
}

/// The case of one `unwinder` shape.
fn unwind(shape: &str) -> Case {
    if shape.starts_with("cleanup-") {
        return cleanup(shape);
    }
    let mut program = Program::new(format!(
        "{shape} frames under _Unwind_Backtrace, as the NetBSD libc unwinds them"
    ));
    let mut tags = TAGS.to_vec();
    if shape == "signal" {
        program.define("_POSIX_C_SOURCE", "200809L");
        program.include("signal.h");
        tags.push("headers");
    }
    for line in UNWIND_DECLS {
        program.top(*line);
    }
    program.top("__attribute__((noinline)) unsigned int f3(unsigned int x) {");
    for line in unwind_body(shape) {
        program.top(*line);
    }
    for line in [
        "    return r * 2u + 1u;",
        "}",
        "",
        "__attribute__((noinline)) unsigned int f2(unsigned int x) {",
        "    return f3(x + 1u) * 3u + x;",
        "}",
        "",
        "__attribute__((noinline)) unsigned int f1(unsigned int x) {",
        "    return f2(x + 1u) * 5u + x;",
        "}",
        "",
        "static volatile int handled;",
        "",
        "static void handler(int sig) {",
        "    handled = (int)(probe() != 0u) + sig;",
        "}",
    ] {
        program.top(line);
    }
    if shape == "signal" {
        program.line("signal(SIGUSR1, handler);");
    } else {
        program.line("(void)handler;");
    }
    program.line("unsigned int r = f1(seed);");
    program.line("unsigned int at = find((void *)probe, 0u);");
    if shape == "signal" {
        program.line("at = find((void *)handler, at);");
    }
    for name in ["f3", "f2", "f1", "main"] {
        program.line(format!("at = find((void *){name}, at);"));
    }
    program.check(Ty::U32, "at < FRAMES", 1);
    program.check(Ty::U32, "r", i128::from(unwind_result(shape)));
    if shape == "signal" {
        program.check(Ty::I32, "handled - SIGUSR1", 1);
    }
    case(Facet::Unwinder, Axes::of([("shape", shape)]), program.finish(), Vec::new(), &[], &tags)
}

/// The case of a cleanup shape, where a thread ends three frames deep.
fn cleanup(shape: &str) -> Case {
    let cancel = shape == "cleanup-cancel";
    let mut program = Program::new(format!(
        "{shape}: cleanup attributes under the forced unwind of {}",
        if cancel { "pthread_cancel" } else { "pthread_exit" }
    ));
    program.define("_POSIX_C_SOURCE", "200809L");
    program.include("pthread.h");
    let mut tags = TAGS.to_vec();
    tags.push("threads");
    tags.push("headers");
    for line in [
        "static unsigned int order;",
        "static volatile unsigned int ready;",
        "",
        "static void undo(unsigned int *level) {",
        "    order = order * 10u + *level;",
        "}",
        "",
        "__attribute__((noinline)) static unsigned int level3(unsigned int x) {",
        "    unsigned int mine __attribute__((cleanup(undo))) = 3u;",
    ] {
        program.top(line);
    }
    if cancel {
        for line in ["    ready = 1u;", "    for (;;) {", "        pthread_testcancel();", "    }"]
        {
            program.top(line);
        }
    } else {
        program.top("    pthread_exit((void *)(unsigned long)(x + mine));");
    }
    for line in [
        "    return x;",
        "}",
        "",
        "__attribute__((noinline)) static unsigned int level2(unsigned int x) {",
        "    unsigned int mine __attribute__((cleanup(undo))) = 2u;",
        "    return level3(x + mine) + 1u;",
        "}",
        "",
        "__attribute__((noinline)) static unsigned int level1(unsigned int x) {",
        "    unsigned int mine __attribute__((cleanup(undo))) = 1u;",
        "    return level2(x + mine) + 1u;",
        "}",
        "",
        "static void *thread_main(void *arg) {",
        "    return (void *)(unsigned long)level1((unsigned int)(unsigned long)arg);",
        "}",
    ] {
        program.top(line);
    }
    program.line("pthread_t thread;");
    program.line("void *result = 0;");
    program.line(format!("pthread_create(&thread, 0, thread_main, (void *){CLEANUP_ARG}ul);"));
    if cancel {
        program.line("while (!ready) {");
        program.line("}");
        program.line("pthread_cancel(thread);");
    }
    program.line("pthread_join(thread, &result);");
    if cancel {
        program.check(Ty::U32, "result == PTHREAD_CANCELED", 1);
    } else {
        program.check(Ty::U32, "(unsigned int)(unsigned long)result", i128::from(CLEANUP_ARG + 6));
    }
    program.check(Ty::U32, "order", 321);
    case(
        Facet::Unwinder,
        Axes::of([("shape", shape)]),
        program.finish(),
        Vec::new(),
        &["-fexceptions", "-pthread"],
        &tags,
    )
}

