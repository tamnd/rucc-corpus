/// What the `fsread` shape prints before its budget line.
fn fsread_result() -> Vec<u32> {
    const BSIZE: u32 = 64;
    let block = |phys: u32, at: u32| (phys.wrapping_mul(31).wrapping_add(at * 7)) as u8;
    let phys = |lbn: u32| if lbn < 12 { 40 - lbn } else { 3 + (lbn - 12) * 2 };
    let size = 20 * BSIZE - 13;
    let (mut sum, mut off, mut reads, mut cached) = (0u32, 0u32, 0u32, false);
    while off < size {
        let n = (size - off).min(100);
        let mut done = 0;
        while done < n {
            let lbn = (off + done) / BSIZE;
            let at = (off + done) % BSIZE;
            let take = (BSIZE - at).min(n - done);
            if lbn >= 12 && !cached {
                reads += 1;
                cached = true;
            }
            reads += 1;
            for i in 0..take {
                sum = sum.wrapping_mul(31).wrapping_add(u32::from(block(phys(lbn), at + i)));
            }
            done += take;
        }
        off += n;
    }
    vec![sum, off, reads]
}

/// What the `lookup` shape prints before its budget line.
fn lookup_result() -> Vec<u32> {
    let dirs: [&[(u32, &str)]; 4] = [
        &[(2, "boot"), (3, "etc"), (0, "gone"), (9, "netbsd")],
        &[(4, "kernel"), (7, "loader"), (8, "boot.conf")],
        &[(13, "fstab")],
        &[(11, "kernel"), (12, "kernel.old")],
    ];
    let lookup = |path: &str| {
        let mut ino = 1u32;
        for name in path.split('/').filter(|name| !name.is_empty()) {
            if ino > 4 {
                return 0;
            }
            let found = dirs[(ino - 1) as usize]
                .iter()
                .find(|&&(entry, entry_name)| entry != 0 && entry_name == name);
            match found {
                Some(&(entry, _)) => ino = entry,
                None => return 0,
            }
        }
        ino
    };
    let paths = [
        "/boot/kernel/kernel",
        "/netbsd",
        "//boot//loader",
        "/boot/kernel/kernel.old",
        "/etc/fstab",
        "/gone",
        "/boot/kern",
        "/netbsd/x",
        "/",
        "/boot/boot.conf",
    ];
    vec![paths.iter().fold(0u32, |sum, path| sum.wrapping_mul(37).wrapping_add(lookup(path)))]
}

/// What the `printf` shape prints before its budget line.
fn printf_result() -> Vec<u32> {
    let mut text =
        format!("boot: netbsd {} {} 0x{:x} k%%\n", -42, 4_000_000_000u32, 0xdead_beefu32);
    for i in -3i32..7 {
        let kind = if i & 1 != 0 { "odd" } else { "even" };
        text.push_str(&format!(
            "[{}:{:x}:{kind}]",
            i * 1001,
            u32::from_ne_bytes(i.wrapping_mul(77).to_ne_bytes())
        ));
    }
    text.push_str("%q");
    let sum =
        text.bytes().fold(0u32, |sum, byte| sum.wrapping_mul(31).wrapping_add(u32::from(byte)));
    vec![sum, u32::try_from(text.len()).unwrap_or(u32::MAX)]
}

/// The state that `parse` keeps between calls.
#[derive(Default)]
struct Parsed {
    opts: u32,
    unit: u32,
    slice: u32,
    part: u32,
    ktype: u32,
    kname: Vec<u8>,
}

/// The `parse` of the shape, over a line ended by a zero, the way a correct build runs it.
fn parse(line: &mut [u8], st: &mut Parsed) -> i32 {
    const FLAGS: &[u8] = b"asvcd";
    let mut arg = 0;
    loop {
        let c = line[arg];
        arg += 1;
        if c == 0 {
            return 0;
        }
        if matches!(c, b' ' | b'\t' | b'\n') {
            continue;
        }
        let mut p = arg;
        while !matches!(line[p], 0 | b'\n' | b' ' | b'\t') {
            p += 1;
        }
        if line[p] != 0 {
            line[p] = 0;
            p += 1;
        }
        if c == b'-' {
            loop {
                let c = line[arg];
                arg += 1;
                if c == 0 {
                    break;
                }
                let Some(i) = FLAGS.iter().position(|&flag| flag == c) else {
                    return -1;
                };
                st.opts ^= 1 << i;
            }
        } else {
            let mut q = arg;
            arg -= 1;
            while line[q] != 0 && line[q] != b'(' {
                q += 1;
            }
            if line[q] != 0 {
                st.ktype = 0;
                if q - arg != 2 {
                    return -1;
                }
                st.ktype = match &line[arg..arg + 2] {
                    b"wd" => 1,
                    b"ad" => 2,
                    b"da" => 3,
                    _ => return -1,
                };
                arg = q + 1;
                if !line[arg].is_ascii_digit() {
                    return -1;
                }
                st.unit = u32::from(line[arg] - b'0');
                arg += 1;
                if line[arg] == b',' {
                    arg += 1;
                    if (b'0'..=b'4').contains(&line[arg]) {
                        st.slice = u32::from(line[arg] - b'0');
                        arg += 1;
                    }
                    if line[arg] == b',' {
                        arg += 1;
                    }
                }
                if (b'a'..=b'h').contains(&line[arg]) {
                    st.part = u32::from(line[arg] - b'a');
                    arg += 1;
                }
                arg += 1;
                if line[arg - 1] != b')' {
                    return -1;
                }
            }
            st.kname.clear();
            while arg < p && line[arg] != 0 && st.kname.len() < 63 {
                st.kname.push(line[arg]);
                arg += 1;
            }
        }
        arg = p;
    }
}

/// What the `parse` shape prints before its budget line.
fn parse_result() -> Vec<u32> {
    let lines = [
        "-sv ad(1,2,c)/boot/loader",
        "  wd(0,e)netbsd -c",
        "-x",
        "da(3)/kernel\t-d",
        "zz(0)/k",
        "ad(9,1,b)/boot/kernel/kernel -a",
    ];
    let mut st = Parsed::default();
    let mut sum = 0u32;
    for line in lines {
        let mut buf = [0u8; 48];
        buf[..line.len()].copy_from_slice(line.as_bytes());
        let r = parse(&mut buf, &mut st);
        let h =
            st.kname.iter().fold(0u32, |h, &byte| h.wrapping_mul(33).wrapping_add(u32::from(byte)));
        let ok = if r == 0 { 1u32 } else { 0 };
        sum = sum
            .wrapping_mul(131)
            .wrapping_add(ok * 7)
            .wrapping_add(st.opts.wrapping_mul(11))
            .wrapping_add(st.unit * 13)
            .wrapping_add(st.slice * 17)
            .wrapping_add(st.part * 19)
            .wrapping_add(st.ktype * 23)
            .wrapping_add(h);
    }
    vec![sum]
}

/// The case of one `boot-sizes` shape.
fn size(shape: &str) -> Case {
    let parts = size_parts(shape);
    let mut source = format!(
        "// {shape} after {}, built with the flag line of boot2 and measured\n// Generated by rucc-corpus. Edit the generator, not this file.\n\n",
        parts.after
    );
    for line in BOOT_IO {
        source.push_str(line);
        source.push('\n');
    }
    source.push_str(BOOT_START);
    source.push('\n');
    source.push_str(parts.code);
    source.push_str("\nint main(void) {\n");
    source.push_str(parts.main);
    source.push_str(&format!(
        "    put_u32((unsigned int)(__stop_corpus_boot - __start_corpus_boot) <= {}u);\n    return 0;\n}}\n",
        parts.budget
    ));
    let mut values = match shape {
        "fsread" => fsread_result(),
        "lookup" => lookup_result(),
        "printf" => printf_result(),
        "parse" => parse_result(),
        _ => unreachable!("{shape}"),
    };
    values.push(1);
    let expected: String = values.iter().map(|value| format!("{value}\n")).collect();
    case(
        Facet::BootSizes,
        Axes::of([("shape", shape)]),
        (source, expected),
        Vec::new(),
        BOOT_FLAGS,
        BOOT_TAGS,
    )
}

